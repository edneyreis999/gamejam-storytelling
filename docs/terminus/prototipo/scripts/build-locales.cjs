const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const base = path.join(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(base, 'editorial', name), 'utf8'));
const records = [];
const bySource = new Map();
const ids = new Set();
function add(record) {
  if (ids.has(record.id)) throw new Error(`Duplicate localization key: ${record.id}`);
  const previous = bySource.get(record.pt);
  if (previous && previous.en !== record.en) throw new Error(`Conflicting translation: ${record.pt}`);
  if (!record.pt || !record.en || !record.id) throw new Error('Incomplete translation');
  const parameters = text => [...text.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');
  if (parameters(record.pt) !== parameters(record.en)) throw new Error(`Parameter mismatch: ${record.id}`);
  records.push(record);
  ids.add(record.id);
  bySource.set(record.pt, record);
}
for (const batch of ['a','b','c']) {
  for (const row of read(`lote-${batch}.json`)) {
    if (row.status !== 'revisado') throw new Error(`Unreviewed text: ${row.id}`);
    add({id:row.id,pt:row.pt,en:row.en});
  }
}
const fixed = {...read('glossario.json').terms, ...read('interface-en.json')};
for (const [pt,en] of Object.entries(fixed)) {
  if (bySource.has(pt)) continue;
  add({id:'ui.'+crypto.createHash('sha256').update(pt).digest('hex').slice(0,16),pt,en,...(/\{\w+\}/.test(pt)?{template:true}:{})});
}
fs.mkdirSync(path.join(base,'locales'),{recursive:true});
fs.writeFileSync(path.join(base,'locales/en-US.js'),`/* Generated by scripts/build-locales.cjs from the editorial catalogs. */\n(function(root) {\n  const records = ${JSON.stringify(records,null,2)};\n  root.TerminusLocale = records;\n  if (typeof module !== 'undefined') module.exports = records;\n})(globalThis);\n`);
console.log(`Localized records: ${records.length}`);
