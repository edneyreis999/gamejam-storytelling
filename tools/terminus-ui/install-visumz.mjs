import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {pluginDefaults,readPlugins,setParameter} from './plugin-parameters.mjs';
import {configurePresentation} from './visumz-presentation.mjs';

const source=process.argv[2];
if(!source)throw Error('Pass the source js/plugins directory.');
const root=path.resolve('rpg-maker/Terminus');
const names=['ElementStatus','Battle','EventsMove','ItemsEquips','MainMenu','SkillsStates'];
const versions=['1.26','1.85','1.60','1.56','1.26','1.48'];
const expandStructs=['BattleLayout'];
const plugins=readPlugins(path.join(root,'js/plugins.js'));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const entries=[],manifest=[];
for(const [i,name] of names.entries()){
    const id=`VisuMZ_1_${name}Core`,file=path.join(source,id+'.js');
    const bytes=fs.readFileSync(file),defaults=pluginDefaults(file,{expandStructs});
    assert(defaults.description.includes(versions[i]),id+' version mismatch');
    const changes=configurePresentation(name,defaults.parameters);
    entries.push({name:id,status:true,...defaults});
    manifest.push({name:id,version:versions[i],sha256:hash(bytes),changes});
}
// Validate every source and configuration before modifying the project.
for(const entry of entries){
    const filename=entry.name+'.js',target=path.join(root,'js/plugins',filename);
    fs.copyFileSync(path.join(source,filename),target);
    assert.equal(hash(fs.readFileSync(target)),manifest.find(m=>m.name===entry.name).sha256);
}
const existing=plugins.filter(p=>!entries.some(e=>e.name===p.name));
assert.equal(existing[0].name,'Coreto_0_CoreEngine');
const globals={ColorCrisis:'#704737',ColorDeath:'#af2933',ColorGaugeBack:'#d3c7b4',ColorHPGauge1:'#af2933',ColorHPGauge2:'#af2933',ColorMPGauge1:'#552070',ColorMPGauge2:'#552070',ColorMPCost:'#552070',ColorPowerUp:'#2a847d',ColorPowerDown:'#af2933',ColorCTGauge1:'#704737',ColorCTGauge2:'#edaa2f',ColorTPGauge1:'#2a847d',ColorTPGauge2:'#2a847d',ColorTPCost:'#2a847d',ColorExpGauge1:'#704737',ColorExpGauge2:'#edaa2f',ColorMaxLvGauge1:'#552070',ColorMaxLvGauge2:'#edaa2f',OutlineColorGauge:'rgba(0,0,0,0)'};
for(const [key,value] of Object.entries(globals))setParameter(existing[0].parameters,['Color:struct',key+':str'],value);
setParameter(existing[0].parameters,['Gold:struct','GoldIcon:num'],382);
setParameter(existing[0].parameters,['Gold:struct','GoldOverlap:str'],'Muito');
setParameter(existing[0].parameters,['Window:struct','TranslucentOpacity:num'],160);
const damageColor="return ['#af2933', '#2a847d', '#552070', '#704737'][arguments[0]] || '#360a0b';";
setParameter(existing[0].parameters,['Color:struct','DamageColor:func'],damageColor);
const ordered=[existing[0],...entries,...existing.slice(1)];
fs.writeFileSync(path.join(root,'js/plugins.js'),'// Generated by RPG Maker.\nvar $plugins =\n'+JSON.stringify(ordered,null,2)+';\n');
fs.writeFileSync('tools/terminus-ui/visumz-manifest.json',JSON.stringify({source,expandStructs,globalColors:globals,globalParameters:{'Gold/GoldIcon':382,'Gold/GoldOverlap':'Muito','Window/TranslucentOpacity':160,'Color/DamageColor':damageColor},plugins:manifest},null,2)+'\n');
console.log(manifest.map(({name,version,sha256,changes})=>({name,version,sha256,overrides:changes.length})));
